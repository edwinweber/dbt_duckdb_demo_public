# dbt assets — Seeds
# ---------------------------------------------------------------------------


@_dbt_multi_asset(
    select="resource_type:seed",
    name="dbt_seeds_assets",
)
def dbt_seeds_assets(
    context: AssetExecutionContext,
    dbt: DbtCliResource,
):
    """Load all dbt seeds (static CSV reference data) into DuckDB.

    Executes ``dbt seed`` against the local DuckDB target.  Seeds are static
    CSV files (e.g. ``publicholiday_dk``, ``LKHS_source_systems``) that are
    loaded into the ``main`` schema.  Run this job whenever the CSV files
    change or on initial setup.
    """
    yield from dbt.cli(["seed", "--log-path", _DBT_LOG_PATH], context=context).stream()


# ---------------------------------------------------------------------------
# dbt assets — Bronze layer
# ---------------------------------------------------------------------------


@_dbt_multi_asset(
    select="bronze",
    name="dbt_bronze_assets",
)
def dbt_bronze_assets(
    context: AssetExecutionContext,
    dbt: DbtCliResource,
):
    """Run all dbt Bronze models (views over the raw Bronze NDJSON files).

    Executes ``dbt build --select bronze`` against the local DuckDB target.
    Bronze models are thin views that read the NDJSON files written by the dlt
    extraction assets via ``read_json_auto``.  They are cheap to rebuild and
    must exist before Silver can run.

    Sources are mapped to dlt extraction asset keys via ``DddDbtTranslator``,
    creating lineage edges:  dlt:afstemning → dbt:bronze/bronze_afstemning.
    """
    yield from dbt.cli(["build", "--log-path", _DBT_LOG_PATH], context=context).stream()


# ---------------------------------------------------------------------------
# dbt assets — Silver layer
# ---------------------------------------------------------------------------


@_dbt_multi_asset(
    select="silver",
    name="dbt_silver_assets",
)
def dbt_silver_assets(
    context: AssetExecutionContext,
    dbt: DbtCliResource,
    config: DbtSilverConfig,
):
    """Run all dbt Silver models (incremental CDC tables + current-version views).

    Executes ``dbt build --select silver`` against the local DuckDB target,
    reading from the Bronze views and writing to incremental Silver tables.

    The run config (:class:`DbtSilverConfig`) turns the delete guard off or
    skips late Bronze files for one run.  Each Silver table's materialization
    carries the rows the run inserted, updated and deleted and the Bronze files
    it processed (:func:`stream_with_silver_row_counts`).
    """
    args = ["build", "--full-refresh"] if config.full_refresh else ["build"]
    args += silver_vars(config.delete_guard, config.skip_late_files)
    invocation = dbt.cli(args + ["--log-path", _DBT_LOG_PATH], context=context)
    yield from stream_with_silver_row_counts(invocation)


# ---------------------------------------------------------------------------
# dbt assets — Gold layer
# ---------------------------------------------------------------------------


@_dbt_multi_asset(
    select="gold",
    name="dbt_gold_assets",
)
def dbt_gold_assets(
    context: AssetExecutionContext,
    dbt: DbtCliResource,
):
    """Run all dbt Gold models (dimensional views + fact table).

    Executes ``dbt build --select gold`` against the local DuckDB target,
    reading from the Silver layer and writing to Gold views.

    Gold models are views so they rebuild cheaply on every run.  The
    ``dbt build`` command also executes the Gold data quality tests (surrogate
    key uniqueness / not-null checks).

    Before the Gold build, the ``bronze_dates`` view is recompiled.  The Gold
    ``date`` dimension is built from that view, and ``bronze_dates`` bakes the
    ``date_spine_start_date`` var into its compiled SQL at build time.  Running
    Gold in isolation would otherwise read a *stale* spine (e.g. after the var
    is widened), leaving ``individual_votes`` rows with no matching ``date`` row
    and failing the FK relationships test.  The recompile is a separate,
    context-less invocation so it is **not** mapped to a Gold asset output —
    ``bronze_dates`` belongs to ``dbt_bronze_assets``; here it is only refreshed
    as an upstream dependency of the Gold ``date`` dimension.

    This asset set must run **after** ``dbt_silver_assets`` — the job
    sequencing in ``jobs.py`` enforces this order.

    ``--exclude data_engineering``: dbt selects every test that references a
    selected model, so the data_engineering relationship tests to ``date`` and
    ``time`` would run here, before ``dbt_data_engineering_assets`` has built
    (or refreshed) the models they test.  They run in that step instead.
    """
    dbt.cli(["run", "--select", "bronze_dates", "--log-path", _DBT_LOG_PATH]).wait()
    args = ["build", "--exclude", "data_engineering", "--log-path", _DBT_LOG_PATH]
    yield from dbt.cli(args, context=context).stream()



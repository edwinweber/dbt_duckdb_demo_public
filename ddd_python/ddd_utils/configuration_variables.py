# Combined mapping of Silver model name → primary key column.
# Used by the Silver Delta Lake export to build the correct LEFT JOIN for
# incremental appends (each source system may have different PK columns).
SILVER_TABLE_PRIMARY_KEYS: dict[str, str] = {
    **{f"silver_ddd_{entity}": pk for entity, pk in DANISH_DEMOCRACY_TABLE_PRIMARY_KEYS.items()},
    **{f"silver_rfam_{entity}": pk for entity, pk in RFAM_TABLE_PRIMARY_KEYS.items()},
}

# SQL queries per Rfam table.
# - Uses SELECT * to let dlt handle schema evolution automatically.
# - The {where_clause} placeholder is replaced at runtime: incremental tables
#   get a date filter, full-extract tables get no filter.
# - Full-extract tables are extracted as-is; Silver detects their changes by
#   comparing each file with the previous one (see dbt_transformations.md §3).
RFAM_TABLE_QUERIES: dict[str, str] = {
    "family": ("SELECT * FROM family{where_clause}"),
    "genome": ("SELECT * FROM genome{where_clause}"),
    "clan": ("SELECT * FROM clan"),
    "clan_membership": ("SELECT * FROM clan_membership"),
    "author": ("SELECT * FROM author"),
    "literature_reference": ("SELECT * FROM literature_reference"),
    "dead_family": ("SELECT * FROM dead_family"),
}

# Import-time invariant guards: catch config drift the moment the module loads.
# Using ValueError (not assert) so these checks survive python -O optimisation.
_expected_dd_pk_keys = {normalize_danish_name(n) for n in DANISH_DEMOCRACY_FILE_NAMES}
if set(DANISH_DEMOCRACY_TABLE_PRIMARY_KEYS) != _expected_dd_pk_keys:
    raise ValueError(
        "DANISH_DEMOCRACY_TABLE_PRIMARY_KEYS keys must match "
        "the normalised form of DANISH_DEMOCRACY_FILE_NAMES"
    )
if set(RFAM_TABLE_PRIMARY_KEYS) != set(RFAM_TABLE_NAMES):
    raise ValueError("RFAM_TABLE_PRIMARY_KEYS keys must match RFAM_TABLE_NAMES")
